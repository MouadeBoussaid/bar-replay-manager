// Normalise BAR engine dumps into src/main/data/unitDefTables.generated.ts.
//
//   node scripts/gen-unitdefs.mjs <dump1.json> [dump2.json ...]
//
// Each <dump> is the output of scripts/dump-unitdefs.lua (run once as a BAR
// widget). One table is emitted per dump, keyed by its GameType string; the
// runtime (src/main/unit-defs.ts) picks the closest one that isn't newer than a
// given replay.

import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const OUT = resolve(here, '../src/main/data/unitDefTables.generated.ts')

const num = (s) => {
  const n = parseFloat(s)
  return Number.isFinite(n) ? n : 0
}

const files = process.argv.slice(2)
if (files.length === 0) {
  console.error('usage: node scripts/gen-unitdefs.mjs <dump.json> [more.json ...]')
  console.error('dumps come from running scripts/dump-unitdefs.lua as a BAR widget')
  process.exit(1)
}

const missing = files.filter((f) => !existsSync(f))
if (missing.length) {
  console.error('file(s) not found:\n  ' + missing.join('\n  '))
  console.error('\nunitdefs_dump.json is written to BAR\'s write directory (next to infolog.txt)')
  console.error('when the dump-unitdefs.lua widget runs. Copy it here, or pass its full path.')
  process.exit(1)
}

/**
 * Accept any of: the widget's unitdefs_dump.json, a springsettings.cfg carrying
 * the `bar_replay_manager_unitdefs` key, or an infolog.txt with the widget's
 * `#####BRM_DUMP_BEGIN#####` … `BRM id,cost,off;` … `#####BRM_DUMP_END#####` block.
 */
function loadDump(file) {
  const raw = readFileSync(file, 'utf8')

  if (raw.includes('#####BRM_DUMP_BEGIN#####')) {
    const begin = raw.match(/#####BRM_DUMP_BEGIN#####\s*(.*)/)
    const gameVersion = (begin?.[1] ?? '').trim()
    const units = {}
    let seen = 0
    for (const line of raw.split(/\r?\n/)) {
      // [t=..][f=..] BRM|<id>|<name>|mc=<x>|bcm=<y>|cm=<z>|w=<n>|fac=<0/1>|bld=<0/1>|com=<0/1>
      const m = line.match(/\bBRM\|(\d+)\|([^|]*)\|(.*)$/)
      if (!m) continue
      seen++
      const id = Number(m[1])
      const kv = Object.fromEntries(m[3].split('|').map((s) => s.split('=')))
      // `ud.cost` (a plain number in current engines) is the trustworthy one;
      // `ud.metalCost` reported ~1000x for some units in the first dump.
      const cost = num(kv.c) || num(kv.ctm) || num(kv.mc) || num(kv.bcm) || 0
      const offensive =
        num(kv.w) > 0 && kv.fac !== '1' && kv.bld !== '1' && kv.com !== '1' ? 1 : 0
      if (cost > 0) units[id] = [Math.round(cost), offensive]
    }
    if (seen === 0) throw new Error(`no "BRM|" lines in ${file} — was infolog.txt overwritten by a later launch?`)
    return { gameVersion, units }
  }

  if (file.toLowerCase().endsWith('.cfg') || raw.includes('bar_replay_manager_unitdefs=')) {
    const m = raw.match(/^\s*bar_replay_manager_unitdefs\s*=\s*(.+)$/m)
    if (!m) throw new Error(`no "bar_replay_manager_unitdefs=" line in ${file} — did the widget run?`)
    return JSON.parse(m[1].trim())
  }

  return JSON.parse(raw)
}

const tables = files.map((file) => {
  const d = loadDump(file)
  const units = {}
  for (const [id, v] of Object.entries(d.units ?? {})) {
    const cost = Array.isArray(v) ? v[0] : v.metalCost
    const offensive = Array.isArray(v) ? v[1] : v.offensive ? 1 : 0
    if (typeof cost === 'number' && cost > 0) {
      units[Number(id)] = [Math.round(cost), offensive ? 1 : 0]
    }
  }
  // BAR replay scripts write GameType as "<gameName> <gameVersion>"; match that.
  const gameVersion = [d.gameName, d.gameVersion].filter(Boolean).join(' ').trim() || String(d.gameVersion ?? '')
  return {
    gameVersion,
    engineVersion: String(d.engineVersion ?? ''),
    units
  }
})

const body = `/* GENERATED by scripts/gen-unitdefs.mjs — do not edit.
 * Source: BAR engine dumps produced by scripts/dump-unitdefs.lua.
 */
export interface UnitDefTable {
  /** The replay's \`[GAME] { GameType }\` string this table was dumped from. */
  gameVersion: string
  engineVersion: string
  /** unitDefID -> [metalCost, offensive ? 1 : 0] */
  units: Record<number, [number, 0 | 1]>
}

export const UNIT_DEF_TABLES: UnitDefTable[] = ${JSON.stringify(tables, null, 2)}
`

writeFileSync(OUT, body)
console.log(`wrote ${OUT}`)
for (const t of tables) {
  console.log(`  ${t.gameVersion || '(no version)'} — ${Object.keys(t.units).length} units`)
}
